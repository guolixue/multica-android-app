#!/usr/bin/env node
/**
 * Bump the mobile app version by +1 patch (0.2.0 → 0.2.1) and rewrite
 * every file that carries it, so the next APK build installs as an update.
 *
 * Files updated (all kept in sync so a direct gradle build AND a future
 * `expo prebuild` both produce the new version):
 *   - package.json (workspace root)          — workspace manifest
 *   - apps/mobile/package.json               — mobile package manifest
 *   - apps/mobile/app.config.ts              — Expo source of truth; feeds
 *                                              `expo prebuild`
 *   - apps/mobile/android/app/build.gradle   — what gradle reads when building
 *                                              the already-generated android/
 *                                              dir directly (this workspace
 *                                              builds with gradle, not a
 *                                              prebuild per build)
 *
 * versionCode is derived from the semver: major*10000 + minor*100 + patch
 * (0.2.1 → 20001). Android requires versionCode to strictly increase across
 * installs; this mapping is monotonic with the patch bump and deterministic
 * (no reading stale gradle values).
 *
 * Note: `android/` is generated by `expo prebuild` and is NOT git-tracked
 * (root .gitignore). On a fresh checkout, run
 * `pnpm -C apps/mobile exec expo prebuild --platform android` once before
 * the first APK build so this script has a build.gradle to update.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const mobileRoot = join(scriptDir, ".."); // apps/mobile
const repoRoot = join(mobileRoot, "..", ".."); // repo root (apps/mobile → apps → root)

const paths = {
  rootPkg: join(repoRoot, "package.json"),
  mobilePkg: join(mobileRoot, "package.json"),
  config: join(mobileRoot, "app.config.ts"),
  gradle: join(mobileRoot, "android", "app", "build.gradle"),
};

// --- read current version from apps/mobile/package.json (single source) ---
const mobilePkg = JSON.parse(readFileSync(paths.mobilePkg, "utf8"));
const versionMatch = /^(\d+)\.(\d+)\.(\d+)$/.exec(mobilePkg.version);
if (!versionMatch) {
  console.error(`[bump-android-version] cannot parse version "${mobilePkg.version}"`);
  process.exit(1);
}
const [, maj, min, pat] = versionMatch.map(Number);
const prevVersion = mobilePkg.version;
const nextVersion = `${maj}.${min}.${pat + 1}`;
const nextCode = maj * 10000 + min * 100 + pat + 1;

// --- package.json (workspace root) ---
try {
  const rootPkg = JSON.parse(readFileSync(paths.rootPkg, "utf8"));
  if (rootPkg.version) {
    rootPkg.version = nextVersion;
    writeFileSync(paths.rootPkg, JSON.stringify(rootPkg, null, 2) + "\n");
  }
} catch {
  // root package.json missing/parse error — not fatal; skip.
}

// --- apps/mobile/package.json ---
mobilePkg.version = nextVersion;
writeFileSync(paths.mobilePkg, JSON.stringify(mobilePkg, null, 2) + "\n");

// --- app.config.ts: version + android.versionCode ---
let config = readFileSync(paths.config, "utf8");
config = config.replace(
  /version:\s*"\d+\.\d+\.\d+"/,
  `version: "${nextVersion}"`,
);
if (/versionCode:\s*\d+/.test(config)) {
  config = config.replace(/versionCode:\s*\d+/, `versionCode: ${nextCode}`);
} else {
  // Insert into the android block right after the package line.
  config = config.replace(
    /(android:\s*\{[^}]*?package:\s*"[^"]+",\n)/,
    `$1      versionCode: ${nextCode},\n`,
  );
}
writeFileSync(paths.config, config);

// --- android/app/build.gradle (present when android/ is generated) ---
let gradleUpdated = false;
try {
  let gradle = readFileSync(paths.gradle, "utf8");
  gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${nextCode}`);
  gradle = gradle.replace(
    /versionName\s+"\d+\.\d+\.\d+"/,
    `versionName "${nextVersion}"`,
  );
  writeFileSync(paths.gradle, gradle);
  gradleUpdated = true;
} catch {
  // android/ not generated yet — skip; app.config.ts carries the version
  // and `expo prebuild` will emit it into build.gradle.
}

const notes = gradleUpdated
  ? "build.gradle updated"
  : "android/ not generated — run `expo prebuild --platform android` first";
console.log(
  `[bump-android-version] ${prevVersion} → ${nextVersion} (versionCode ${nextCode}); ${notes}`,
);
